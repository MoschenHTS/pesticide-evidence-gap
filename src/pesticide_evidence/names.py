def _ALNUM(x):
    """Text reduced to lowercase letters, digits and commas."""
    return re.sub(r"[^a-z0-9,]", "", x)


PREFIX = sorted(((_ALNUM(v.lower()), canonical(v)) for v in C_OF if len(v) >= 6 or v == "2,4-D"), key=lambda t: -len(t[0]))
PREFIX_MANUAL = {"parathionmethyl": "methyl parathion", "methylparathion": "methyl parathion", "azinphosmethyl": "azinphos-methyl", "azinphosethyl": None}


def to_canonical(name):
    """Canonical ingredient name for a name in English, Portuguese or another spelling, or None when no rule matches."""
    raw = strip_accents(unicodedata.normalize("NFKC", str(name))).lower().strip()
    if raw in MANUAL:
        return MANUAL[raw]
    raw = PREF_PT.sub("", raw)
    raw2 = SALT_PT.sub("", raw)
    if raw2 in MANUAL:
        return MANUAL[raw2]
    z = _ALNUM(raw)
    if z.startswith(("copper", "cupric", "cuprous", "cuivre")):
        return "copper"
    for k, v in PREFIX_MANUAL.items():
        if z.startswith(k):
            return v
    for cand in (raw, raw2, ISOMER.sub("", raw2)):
        for v in C_OF:
            if v.lower() == cand:
                return canonical(v)
        k = skel(cand)
        hit = INDEX.get(k)
        if hit and len(hit) == 1:
            return next(iter(hit))
        if hit:

            def nz(x):
                """Name reduced to letters with common spelling variants merged."""
                return re.sub(r"[^a-z]", "", x.replace("y", "i").replace("ph", "f").replace("th", "t").replace("ch", "c").replace("k", "c"))

            sc = sorted(((difflib.SequenceMatcher(None, nz(cand), nz(strip_accents(h).lower())).ratio(), h) for h in hit), reverse=True)
            if sc[0][0] >= 0.75 and sc[0][0] - sc[1][0] >= 0.08:
                return sc[0][1]
    for p, cn in PREFIX:
        if z.startswith(p) and len(z) - len(p) <= 18:
            return cn
    return None
