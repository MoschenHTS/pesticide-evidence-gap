def canonical(name):
    """Canonical ingredient name after the alias table."""
    return ALIAS.get(name, name)


def class_of_name():
    """name -> (group, class); each name is unique by construction."""
    out = {}
    for (g, c), L in NAMES.items():
        for n in L:
            assert n not in out, f"{n} in two classes"
            out[n] = (g, c)
    return out


def focal_classes():
    """Pairs of group and class for the core pesticide groups."""
    return [(g, c) for (g, c) in NAMES if g in CORE_GROUPS]


C_OF = class_of_name()


def strip_accents(s):
    """Text with combining accents removed."""
    return "".join(c for c in unicodedata.normalize("NFD", str(s)) if unicodedata.category(c) != "Mn")


def skel(s):
    """Consonant skeleton of a name, used to match spelling variants across languages."""
    s = strip_accents(s).lower()
    s = re.sub(r"\(.*?\)", "", s)
    s = s.replace("ph", "f").replace("ck", "c").replace("k", "c").replace("qu", "c").replace("ch", "c")
    s = re.sub(r"[^a-z0-9]", "", s)
    s = re.sub(r"[aeiouyhw]", "", s)
    s = re.sub(r"(.)\1+", r"\1", s)
    return re.sub(r"m$", "n", s)


