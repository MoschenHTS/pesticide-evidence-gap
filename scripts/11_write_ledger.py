"""Stage 11. Write results/NUMBERS_LEDGER.md, the single list of numbers quoted in the manuscript.

Reads results/numbers.json (stage 06), results/event_studies.json (stage 07), results/sensitivity.json (stage 08) and results/brazil.json (stage 09).
"""

import json

import numpy as np

from pesticide_evidence.config import path

ABSENT = "absent from Northern registers"


def ratio(t):
    """Format a ratio and its 95% interval as text."""
    return f"{t[0]:.2f} ({t[1]:.2f}-{t[2]:.2f})"


def section(lines, title, *body):
    """Append a titled block of lines to the ledger."""
    lines.append(f"## {title}")
    lines.extend(body)
    lines.append("")


def build(N, E):
    """Assemble the ledger text from the cross-sectional numbers N and the event-study results E."""
    L = ["# Numbers ledger (generated by scripts/11_write_ledger.py)", ""]
    s = N["sample"]
    section(
        L,
        "Sample",
        f"n = {s['n']}: authorized {s['authorized']}, withdrawn {s['withdrawn: hazard/treaty']}, lapsed {s['lapsed: other reason']}, absent {s[ABSENT]}; "
        "model: Poisson pseudo-ML, ln Southern use, ln Northern use+1, ln market age, target class, crop-group shares; robust standard errors.",
    )

    h = N["headline"]
    rows = ["| outcome | absent | lapsed | withdrawn |", "|---|---|---|---|"]
    for key, label in (
        ("combined_tox_pubmed_plus_zh", "PubMed toxicity + Chinese-language toxicity (primary)"),
        ("pubmed_tox_only", "PubMed toxicity only"),
        ("all_topics_combined", "All topics (PubMed + Chinese)"),
        ("cas_registry_pubmed", "PubMed CAS-registry (name-independent)"),
    ):
        rows.append(f"| {label} | {ratio(h[key]['absent'])} | {ratio(h[key]['lapsed'])} | {ratio(h[key]['withdrawn'])} |")
    median = ", ".join(f"{k} {v:g}" for k, v in N["raw_median_papers"].items())
    section(
        L,
        "Headline ratios vs authorized (95% CI)",
        *rows,
        "",
        f"Elasticity of papers to Southern use (primary): {h['combined_tox_pubmed_plus_zh']['elasticity_south_use']}. Raw median papers: {median}",
    )

    w = N["windows"]
    section(
        L,
        "Five-year windows (PubMed toxicity query only; absent / lapsed / withdrawn)",
        *[f"- {k}: absent {ratio(v['absent'])}; lapsed {ratio(v['lapsed'])}; withdrawn {ratio(v['withdrawn'])}" for k, v in w.items() if k != "n"],
    )

    r = N["registers"]
    b = r["US_over_EU_joint"]
    section(
        L,
        "Registers (ratio vs authorized in that register)",
        *[f"- {k}: {ratio(list(r[k].values())[0])}" for k in ("not_EU", "not_US", "not_CA", "none_of_three")],
        "- joint (EU, US, CA): " + "; ".join(f"{k} {ratio(v)}" for k, v in r["joint_EU_US_CA"].items()),
        f"- US/EU ratio in joint model ({b['reps']} bootstrap reps): {b['median']} ({b['ci'][0]}-{b['ci'][1]}); US ratio below EU ratio in {b['share_US_lt_EU'] * 100:.0f}% of reps",
    )

    fo, fd = N["funders_openalex"], N["funders_diff"]
    section(
        L,
        f"Funders (OpenAlex; {fo['n_ingredients']} ingredients; absent {fo['groups'].get(ABSENT)})",
        "- ratios absent vs authorized: " + "; ".join(f"{k} {ratio(fo[k])}" for k in ("all", "northern", "southern", "industry", "unclassified")),
        "- share of works with a Northern funder: " + ", ".join(f"{k} {v * 100:.1f}%" for k, v in fo["share_works_northern_funder"].items()),
        "- share with a Southern funder: " + ", ".join(f"{k} {v * 100:.1f}%" for k, v in fo["share_works_southern_funder"].items()),
        f"- Northern-funded vs Southern-funded gap (stacked, clustered by ingredient): absent ratio {fd['absent_ratio_northern_funded']:.2f} vs {fd['absent_ratio_southern_funded']:.2f}; "
        f"ratio of ratios {fd['ratio_of_ratios_N_over_S']:.2f} ({fd['ci'][0]:.2f}-{fd['ci'][1]:.2f}), z={fd['z']}",
    )

    gs = N["group_shares"]
    section(
        L,
        "Shares of Southern mass and of toxicity papers, by group (sample)",
        "; ".join(
            f"{g} mass {v['mass'] * 100:.1f}%, papers {v['papers'] * 100:.1f}%, ratio {v['papers_per_mass']:.2f}, median market age {v['median_age']:.0f} years"
            for g, v in gs.items()
        ),
    )
    sf = N["selection_flow"]
    section(
        L,
        "Selection of papers for the event-study corpus",
        f"{sf['queries']} queries, {sf['records']} records; {sf['excluded_by_rule']} excluded by the first rule filter for content, {sf['excluded_other']} for other reasons, "
        f"{sf['rule_retained']} passing it; removed by the selection rules: "
        + ", ".join(f"{k} {v}" for k, v in sf["removed_by_step"].items())
        + f"; {sf['selected']} selected",
    )
    sp = N.get("model_specification")
    if sp:
        section(
            L,
            "Primary model: coefficients, collinearity and alternative forms",
            "; ".join(f"{k} ratio {v['ratio']:.2f} ({v['lo']:.2f}-{v['hi']:.2f})" for k, v in sp["coefficients"].items())
            + f"; maximum VIF {sp['vif_max']['value']:.1f} ({sp['vif_max']['name']}), median {sp['vif_median']:.1f}; "
            + "; ".join(f"{k}: absent {v['absent'][0]:.2f} ({v['absent'][1]:.2f}-{v['absent'][2]:.2f})" for k, v in sp["alternative_forms"].items()),
        )
    fo = N["funders_openalex"]
    if "share_works_with_listed_funder" in fo:
        section(
            L,
            "Funder coverage in OpenAlex toxicity works",
            "share with a listed funder by group: "
            + ", ".join(f"{g} {v * 100:.1f}%" for g, v in fo["share_works_with_listed_funder"].items())
            + f"; absent ratio among works with a listed funder {fo['absent_ratio_works_with_listed_funder'][0]:.2f} "
            + f"({fo['absent_ratio_works_with_listed_funder'][1]:.2f}-{fo['absent_ratio_works_with_listed_funder'][2]:.2f}); "
            + "Northern-funder share of funded works: "
            + ", ".join(f"{g} {v * 100:.1f}%" for g, v in fo["northern_funder_share_of_funded_works"].items()),
        )
    fc = N.get("funder_name_check")
    if fc:
        section(
            L,
            "Funder-name classification check",
            f"{fc['names']} most frequent funder names carry {fc['mention_share'] * 100:.1f}% of {fc['mentions']} funder mentions; "
            f"the name-pattern rule agreed with the hand classification for {fc['agree']} of {fc['names']} names ({fc['agree'] / fc['names'] * 100:.0f}%)",
        )
    if "balance" in E:
        section(
            L,
            "Event study balance, exits not listed under the treaties (treated, control, standardized difference)",
            "; ".join(f"{k} {v['treated']:.2f}, {v['control']:.2f}, {v['std_diff']:.2f}" for k, v in E["balance"].items() if isinstance(v, dict)),
        )
    bt = N["bombardi_top5"]
    section(
        L,
        "Five best-selling ingredients in Brazil that are not approved in the EU (named by Bombardi 2023): papers against the authorized-only fit",
        "; ".join(
            f"{a} ({v['group']}; EU {int(v['eu'])}, US {int(v['us'])}, CA {int(v['ca'])}) {v['observed']:.0f} vs {v['expected_authorized_fit']:.0f} expected, ratio {v['ratio']:.2f}"
            for a, v in bt.items()
        ),
    )
    if "brazil" in N:
        br = N["brazil"]
        pr = br["primary"]
        g, r, j = pr["groups"], pr["registers"], pr["registers"]["joint"]
        section(
            L,
            f"Brazilian subsample (Brazilian applied mass of at least {br['min_brazil_use_t']} t, atlas reported rows; ln Brazilian use in place of ln Southern use)",
            f"n = {pr['n']} ({pr['by_group']}); ratios vs authorized: absent {ratio(g['absent'])}, lapsed {ratio(g['lapsed'])}, withdrawn {ratio(g['withdrawn'])}; elasticity of papers to Brazilian use {pr['elasticity_brazil_use']:.2f}",
            f"Register contrasts: not_EU {ratio(r['not_EU'])}; not_US {ratio(r['not_US'])}; not_CA {ratio(r['not_CA'])}; joint not_EU {ratio(j['not_EU'])}, not_US {ratio(j['not_US'])}, not_CA {ratio(j['not_CA'])}",
            f"Pesticides not approved in the EU: {pr['not_eu_n']} of {pr['n']}, of which {pr['not_eu_us_registered_n']} registered in the US",
            *(
                f"Sensitivity, {'any reported Brazilian use' if not v['threshold_t'] else 'Brazilian use of at least ' + str(v['threshold_t']) + ' t'}: n = {v['n']}; absent {ratio(v['groups']['absent'])}; not_EU {ratio(v['registers']['not_EU'])}; not_US {ratio(v['registers']['not_US'])}"
                for v in br["sensitivity"].values()
            ),
            "Brazilian applied mass of the five best-sellers (t): " + "; ".join(f"{a} {v['brazil_t']:.0f}" for a, v in br["best_sellers"].items()),
        )
    ai = N["atlas_imputation"]
    section(
        L,
        "Atlas coverage and imputation (Fantke et al. preprint, Table S12)",
        f"{ai['countries_reported']} countries with reported data, {ai['countries_imputed']} with imputed data only ({ai['imputed_share_of_atlas_mass'] * 100:.1f}% of atlas mass); sub-Saharan Africa {ai['ssa_countries_reported']} reported "
        f"({ai['ssa_reported_kt_all_ingredients']:.1f} kt) and {ai['ssa_countries_imputed']} imputed ({ai['ssa_imputed_kt_all_ingredients']:.1f} kt); imputed Southern kt in sample ingredients {ai['sample_imputed_south_kt_by_group']}; "
        f"ratios with imputed use added: absent {ai['ratios_with_imputed_use']['absent'][0]:.2f} ({ai['ratios_with_imputed_use']['absent'][1]:.2f}-{ai['ratios_with_imputed_use']['absent'][2]:.2f}), "
        f"lapsed {ai['ratios_with_imputed_use']['lapsed'][0]:.2f}, withdrawn {ai['ratios_with_imputed_use']['withdrawn'][0]:.2f}",
    )
    mp = N["missing_papers"]
    section(
        L,
        "Missing papers (absent ingredients, primary model with the absent term set to zero)",
        f"{mp['n_absent']} ingredients; observed {mp['observed']:.0f} papers, expected {mp['expected']:.0f}, missing {mp['missing']:.0f}; "
        f"{sum(v['observed'] < v['expected'] for v in mp['by_ingredient'].values())} of {mp['n_absent']} below expected; largest shortfalls "
        + ", ".join(
            f"{a} ({v['observed']:.0f} vs {v['expected']:.0f})" for a, v in sorted(mp["by_ingredient"].items(), key=lambda kv: kv[1]["observed"] - kv[1]["expected"])[:4]
        ),
    )
    ca = N["country_absent_share"]
    top = ", ".join(f"{c} {v * 100:.1f}%" for c, v in ca["top_by_absent_mass"].items())
    section(
        L,
        "Absent-ingredient share of national applied mass (reported atlas rows, non-Northern countries)",
        f"{ca['countries']} countries; largest absent mass: {top}; top three countries hold {ca['share_in_top_three_of_absent_mass'] * 100:.1f}% of absent Southern mass",
    )

    m = N["mass"]
    section(
        L,
        "Mass",
        f"446 ingredients, {m['atlas_kt_446_ingredients']} kt (reported rows); South share {m['south_share'] * 100:.1f}%; "
        f"China share of absent Southern mass {m['china_share_of_absent_south_mass'] * 100:.1f}%",
    )

    section(
        L,
        "Crops (mass share in absent ingredients; global toxicity papers per kt applied, mass-weighted: absent vs authorized)",
        *[f"- {k}: {v['kt']} kt; absent {v['absent_share'] * 100:.1f}%; papers/kt {v['ppk_absent']} vs {v['ppk_authorized']}" for k, v in N["crops"].items()],
    )

    c, a = N["coverage"], N["coverage"]["africa"]
    section(
        L,
        "Coverage",
        f"Sub-Saharan Africa: {a['atlas_countries']} of {a['wb_countries']} countries in atlas, {a['atlas_kt']} kt = {a['share_atlas_mass'] * 100:.1f}% of atlas mass; "
        f"FAOSTAT SSA = {a['fao_share_world'] * 100:.1f}% of FAO regional-sum total ({c['fao_total_kt_region_sum']} kt); Nigeria {a['nigeria_fao_kt']} kt (FAO) absent from atlas",
        "- atlas / FAO by region: " + "; ".join(f"{k} {v['atlas_over_fao']}" for k, v in c["by_region"].items() if v["atlas_over_fao"] is not None),
        "- atlas / GloPUT by region: " + "; ".join(f"{k} {v['atlas_over_glopu']}" for k, v in c["by_region"].items() if v.get("atlas_over_glopu") is not None),
        f"- GloPUT sub-Saharan Africa {a['glopu_ssa_kt']} kt (2016-2019 mean); Nigeria {a['nigeria_glopu_kt']} kt",
    )

    ev = [
        f"- Stacked, {k}: nT={v['nT']}; North {v['North']:.1f}% ({v['North_ci'][0]:.1f},{v['North_ci'][1]:.1f}), South {v['South']:.1f}% ({v['South_ci'][0]:.1f},{v['South_ci'][1]:.1f}); "
        f"North-South difference z={v['diff_z']:.2f}; placebo ({v['placebo_n']} runs) SD North {v['placebo_North']['sd']:.2f}, one-sided p North {v['p_North_le']:.3f}, difference p {v['p_diff_le']:.3f}; "
        f"placebo-calibrated North ({v['North_cal_ci'][0]:.0f},{v['North_cal_ci'][1]:.0f}), South ({v['South_cal_ci'][0]:.0f},{v['South_cal_ci'][1]:.0f})"
        for k, v in E["stacked"].items()
    ]
    rt = E["review_timing"]

    def pc_ci(b, se):
        """Percentage change interval from a log coefficient and its standard error, as text."""
        return f"{(np.exp(b - 1.96 * se) - 1) * 100:.1f}, {(np.exp(b + 1.96 * se) - 1) * 100:.1f}"

    ev.append(
        f"- Review timing (EU scheduled date; {int(rt['real']['nT'])} treated, {int(rt['real']['nC'])} controls): North {rt['North_pct']:.1f}% ({pc_ci(rt['real']['bN'], rt['real']['seN'])}), South {rt['South_pct']:.1f}% ({pc_ci(rt['real']['bS'], rt['real']['seS'])}); "
        f"label permutation ({rt['perm_n']}): one-sided p North {rt['p_N_le']:.3f} ({round(rt['p_N_le'] * rt['perm_n'])} of {rt['perm_n']} as extreme), South {rt['p_S_le']:.2f}, difference {rt['p_diff_le']:.3f}"
    )
    section(L, "Event studies (Poisson pseudo-ML, 95% CI from model; placebo-calibrated p)", *ev)
    et = E["event_time"]
    section(
        L,
        "Event time (stacked design, exits not listed under the treaties; change in papers relative to the year before exit)",
        *[f"- {who}: " + "; ".join(f"{k} {v['pct']:.1f}% ({v['lo']:.1f}, {v['hi']:.1f})" for k, v in et[who].items()) for who in ("North", "South")],
    )

    if "sensitivity" in N:
        section(
            L,
            "Sensitivity analyses of the primary result (absent ratio)",
            *[
                f"- {k}: n={v['n']}; absent {ratio(v['absent'])}; lapsed {v['lapsed'][0]:.2f}; withdrawn {v['withdrawn'][0]:.2f}" if "absent" in v else f"- {k}: {v}"
                for k, v in N["sensitivity"].items()
            ],
        )

    H = N["human"]
    hi = H["tox_hazard_interaction"]
    labels = (("human", "Humans[MeSH]"), ("epi", "human epidemiology/biomonitoring"), ("poison", "clinical poisoning"), ("mamm", "rodent toxicity"))
    section(
        L,
        "Human-health relevance (PubMed counts 2005-2025; ratios absent / lapsed / withdrawn vs authorized)",
        *[
            f"- {lab}: absent {ratio(H[k]['absent'])}; lapsed {ratio(H[k]['lapsed'])}; withdrawn {ratio(H[k]['withdrawn'])}; share of ingredients with zero papers: "
            + ", ".join(f"{g.split(' ')[0]} {x * 100:.0f}%" for g, x in H["zero_paper_share_by_group"][k].items())
            for k, lab in labels
        ],
        f"- Hazard interaction (WHO Ia/Ib/II) on the primary toxicity outcome: absent {ratio(hi['absent'])} (non-hazardous); hazardous main effect {ratio(hi['hazardous_main'])}; absent x hazardous {ratio(hi['absent_x_hazardous'])}",
        f"- Southern mass of WHO Ia/Ib/II ingredients with <=20 human papers: {H['mass_hazardous_thin_human']['share_of_sample_South_mass'] * 100:.1f}% of sample Southern mass; kt by group {H['mass_hazardous_thin_human']['by_group_kt']}",
    )

    rc = N["register_crosscheck"]
    section(
        L,
        "Register classification cross-check (independently compiled table, 2026-10-02)",
        f"{rc['matched_n']} of {rc['sample_n']} sample ingredients matched; agreement EU {rc['agreement']['EU'] * 100:.1f}%, US {rc['agreement']['US'] * 100:.1f}%, Canada {rc['agreement']['Canada'] * 100:.1f}%, "
        f"any register {rc['agreement']['any register'] * 100:.1f}%; absent-group ingredients matched {rc['absent_matched_n']}, registered in the independent table {rc['absent_registered_in_independent_table']}; "
        f"disagreements: {', '.join(rc['disagreements_any_register'])}",
    )
    return L


def funder_name_check():
    """Agreement of the funder rules with the hand-checked classes for the 150 most-mentioned funders, and the share of funder mentions they cover."""
    from collections import Counter

    from pesticide_evidence.funders import CHECKED, classify_funder_by_rule

    counts = json.load(open(path("interim", "openalex", "funder_counts.json")))
    mentions = Counter()
    for rec in counts.values():
        for _, name, n in rec["funders"]:
            mentions[name] += n
    top = [name for name, _ in mentions.most_common(150)]
    return {
        "names": len(top),
        "mentions": sum(mentions.values()),
        "mention_share": sum(mentions[n] for n in top) / sum(mentions.values()),
        "agree": sum(classify_funder_by_rule(n) == CHECKED[n] for n in top),
    }


if __name__ == "__main__":
    numbers = json.load(open(path("results", "numbers.json")))
    sensitivity = path("results", "sensitivity.json")
    if sensitivity.exists():
        numbers["sensitivity"] = json.load(open(sensitivity))["sensitivity"]
    brazil = path("results", "brazil.json")
    if brazil.exists():
        numbers["brazil"] = json.load(open(brazil))
    numbers["funder_name_check"] = funder_name_check()
    events = json.load(open(path("results", "event_studies.json")))
    spec_file = json.load(open(sensitivity)) if sensitivity.exists() else {}
    if "model_specification" in spec_file:
        numbers["model_specification"] = spec_file["model_specification"]
    out = path("results", "NUMBERS_LEDGER.md")
    out.write_text("\n".join(build(numbers, events)) + "\n")
    print(f"wrote {out}")
